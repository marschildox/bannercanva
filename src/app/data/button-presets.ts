// Button preset templates based on common button styles

export interface ButtonPreset {
  id: string;
  name: string;
  variant: 'solid' | 'gradient' | 'outline';

  // Colors
  bgColor: string;
  textColor: string;
  borderColor?: string;

  // Gradient (if variant is 'gradient')
  gradientFrom?: string;
  gradientTo?: string;
  gradientDirection?: 'to-r' | 'to-l' | 'to-t' | 'to-b' | 'to-br' | 'to-bl';

  // Border
  borderWidth: number;
  borderRadius: number;

  // Shadow
  shadowEnabled: boolean;
  shadowColor?: string;
  shadowBlur?: number;
  shadowOffsetX?: number;
  shadowOffsetY?: number;

  // Typography
  fontFamily?: string;
  fontWeight?: number;
  fontSize?: number; // percentage of base
  letterSpacing?: number;
  textShadow?: string;
}

